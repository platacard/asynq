// sortedGroupStats returns the group stats sorted by group name: the order of
// groups returned by GroupStats is not defined.
func sortedGroupStats(r *RDB, qname string) ([]*GroupStat, error) {
	stats, err := r.GroupStats(qname)
	sort.Slice(stats, func(i, j int) bool { return stats[i].Group < stats[j].Group })
	return stats, err
}

// currentStatsWithoutMemory returns the queue stats with the memory usage
// replaced by 1 if it is positive: the memory usage depends on the length of
// key names, so it differs between prefixes.
func currentStatsWithoutMemory(r *RDB, qname string) (*Stats, error) {
	stats, err := r.CurrentStats(qname)
	if stats != nil && stats.MemoryUsage > 0 {
		stats.MemoryUsage = 1
	}
	return stats, err
}

// The memory usage is not compared in the mirror test, because it depends on
// the length of key names. Instead, check that it accounts for tasks in every
// state under the custom prefix.
func TestRDBWithPrefixMemoryUsage(t *testing.T) {
	ctx := context.Background()
	states := []struct {
		state string
		setup func(r *RDB, qname string) error
	}{
		{"pending", func(r *RDB, qname string) error {
			return r.Enqueue(ctx, newPrefixTestMessage("id", "type", qname))
		}},
		{"active", func(r *RDB, qname string) error {
			if err := r.Enqueue(ctx, newPrefixTestMessage("id", "type", qname)); err != nil {
				return err
			}
			_, _, err := r.Dequeue(qname)
			return err
		}},
		{"scheduled", func(r *RDB, qname string) error {
			return r.Schedule(ctx, newPrefixTestMessage("id", "type", qname), time.Now().Add(time.Hour))
		}},
		{"retry", func(r *RDB, qname string) error {
			if err := r.Enqueue(ctx, newPrefixTestMessage("id", "type", qname)); err != nil {
				return err
			}
			msg, _, err := r.Dequeue(qname)
			if err != nil {
				return err
			}
			return r.Retry(ctx, msg, time.Now().Add(time.Hour), "error", true)
		}},
		{"archived", func(r *RDB, qname string) error {
			if err := r.Enqueue(ctx, newPrefixTestMessage("id", "type", qname)); err != nil {
				return err
			}
			msg, _, err := r.Dequeue(qname)
			if err != nil {
				return err
			}
			return r.Archive(ctx, msg, "error")
		}},
		{"completed", func(r *RDB, qname string) error {
			msg := newPrefixTestMessage("id", "type", qname)
			msg.Retention = int64(time.Hour.Seconds())
			if err := r.Enqueue(ctx, msg); err != nil {
				return err
			}
			msg, _, err := r.Dequeue(qname)
			if err != nil {
				return err
			}
			return r.MarkAsComplete(ctx, msg)
		}},
		{"aggregating", func(r *RDB, qname string) error {
			msg := newPrefixTestMessage("id", "type", qname)
			msg.GroupKey = "g"
			return r.AddToGroup(ctx, msg, msg.GroupKey)
		}},
	}
	for _, prefix := range testKeyPrefixes {
		t.Run(prefix, func(t *testing.T) {
			global := setup(t)
			defer global.Close()
			r := NewRDBWithPrefix(global.client, prefix)
			for _, s := range states {
				qname := "only-" + s.state
				if err := s.setup(r, qname); err != nil {
					t.Fatalf("%s: setup: %v", s.state, err)
				}
				// The data of other queues stays in the database, but each queue only has a task in one state.
				if err := r.client.Del(ctx, r.Keys().ProcessedTotalKey(qname), r.Keys().FailedTotalKey(qname)).Err(); err != nil {
					t.Fatal(err)
				}
				usage, err := r.memoryUsage(qname)
				if err != nil {
					t.Fatalf("%s: memoryUsage: %v", s.state, err)
				}
				if usage <= 0 {
					t.Errorf("%s: memoryUsage(%q) = %d, want a positive value", s.state, qname, usage)
				}
			}
			assertNoKeysOutsidePrefix(t, r.client, prefix)
		})
	}
}

