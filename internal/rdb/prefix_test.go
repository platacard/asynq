func TestRDBWithPrefixCancelation(t *testing.T) {
	for _, prefix := range testKeyPrefixes {
		t.Run(prefix, func(t *testing.T) {
			global := setup(t)
			// Close the connection after the subscriptions are closed.
			t.Cleanup(func() { global.Close() })
			custom := NewRDBWithPrefix(global.client, prefix)

			subscribe := func(r *RDB) <-chan *redis.Message {
				pubsub, err := r.CancelationPubSub()
				if err != nil {
					t.Fatalf("CancelationPubSub: %v", err)
				}
				t.Cleanup(func() { pubsub.Close() })
				return pubsub.Channel()
			}
			globalCh := subscribe(global)
			customCh := subscribe(custom)

			// Pub/Sub channels are shared by all redis databases, so tests
			// running in parallel against other databases may publish to the same
			// channels. Messages with payloads from other test runs are ignored.
			customTask := "custom-" + uuid.NewString()
			globalTask := "global-" + uuid.NewString()
			ours := map[string]bool{customTask: true, globalTask: true}
			receive := func(ch <-chan *redis.Message, timeout time.Duration) (string, bool) {
				deadline := time.After(timeout)
				for {
					select {
					case msg := <-ch:
						if ours[msg.Payload] {
							return msg.Payload, true
						}
					case <-deadline:
						return "", false
					}
				}
			}
			expectMessage := func(name string, ch <-chan *redis.Message, want string) {
				t.Helper()
				got, ok := receive(ch, 5*time.Second)
				if !ok {
					t.Errorf("%s did not receive %q", name, want)
				} else if got != want {
					t.Errorf("%s received %q, want %q", name, got, want)
				}
			}
			expectNoMessage := func(name string, ch <-chan *redis.Message) {
				t.Helper()
				if got, ok := receive(ch, 200*time.Millisecond); ok {
					t.Errorf("%s received unexpected message %q", name, got)
				}
			}

			if err := custom.PublishCancelation(customTask); err != nil {
				t.Fatalf("custom.PublishCancelation: %v", err)
			}
			expectMessage("custom subscriber", customCh, customTask)
			expectNoMessage("global subscriber", globalCh)

			if err := global.PublishCancelation(globalTask); err != nil {
				t.Fatalf("global.PublishCancelation: %v", err)
			}
			expectMessage("global subscriber", globalCh, globalTask)
			expectNoMessage("custom subscriber", customCh)
		})
	}
}

